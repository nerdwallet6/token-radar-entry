/**
 * FDV/TVL multiples by category, matched on the category keyword (first match wins, most specific
 * first). The market pays more per dollar of TVL for categories whose TVL is sticky, revenue-bearing
 * or scarce, and less for categories that are mostly pass-through plumbing:
 *
 *   1.6  Prediction Market — scarce, attention-driven; a market's TVL is its liquidity and its moat.
 *   1.5  Perpetuals / Derivatives — leveraged flow pays fees on every dollar of open interest.
 *   1.5  RWA — real-world yield is the scarcest TVL in DeFi; buyers pay up for it.
 *   1.4  Basis Trading — delta-neutral yield with a real, auditable spread.
 *   1.4  Restaking (incl. Liquid Restaking, Restaked BTC) — TVL is locked and yield-stacked.
 *   1.35 Synthetics / Options — structured products, high fee per dollar locked.
 *   1.3  Liquid Staking — the stickiest TVL in DeFi; the LST itself becomes money.
 *   1.3  AI Agents / Decentralized AI — speculative premium, small but fast-growing niche.
 *   1.2  Lending / CDP / Collateral — proven fee model, deep and durable TVL.
 *   1.2  Launchpad — TVL is deal flow, not deposits; a launch premium applies.
 *   1.15 Yield / Yield Aggregator / Leveraged Farming — real yield, but mercenary capital.
 *   1.1  Staking / Staking Pool — steady, low-fee TVL.
 *   1.1  Privacy — scarce, but small addressable TVL.
 *   1.0  Dexs, Stablecoins, Insurance, Payments, Indexes — the default: deep TVL, thin fees.
 *   0.9  Farm, Governance Incentives, Token Locker, OTC, Reserve Currency — niche or
 *        pass-through TVL that rarely converts into a valuable token.
 *   0.8  Chain, NFT Marketplace — infra or a thin market, not a token's TVL.
 *   0.75 Bridge / Cross Chain Bridge / Canonical Bridge — pass-through volume; TVL is transient
 *        and the fee take is a few basis points, so the market discounts it hardest.
 *   0.7  CEX — excluded from the board anyway; listed only so the lookup is total.
 *
 * Anything unlisted defaults to 1.0. The range is 0.7–1.6 by construction.
 */
export const CATEGORY_MULTIPLIERS: ReadonlyArray<readonly [keyword: string, multiple: number]> = [
  ['prediction', 1.6],
  ['perpetual', 1.5],
  ['derivative', 1.5],
  ['rwa', 1.5],
  ['basis trad', 1.4],
  ['restak', 1.4],
  ['synthetic', 1.35],
  ['options', 1.35],
  ['liquid staking', 1.3],
  ['ai agent', 1.3],
  ['decentralized ai', 1.3],
  ['lending', 1.2],
  ['cdp', 1.2],
  ['collateral', 1.2],
  ['launchpad', 1.2],
  ['yield', 1.15],
  ['leveraged farm', 1.15],
  ['staking', 1.1],
  ['privacy', 1.1],
  ['indexes', 0.9],
  ['farm', 0.9],
  ['governance', 0.9],
  ['token locker', 0.9],
  ['otc', 0.9],
  ['reserve currency', 0.9],
  ['bridge', 0.75],
  ['chain', 0.8],
  ['nft marketplace', 0.8],
  ['cex', 0.7],
];

/**
 * The category multiple for a protocol: first keyword match wins, 1.0 when nothing matches.
 * A keyword must start at a word boundary, so "Onchain Capital Allocator" does not trip the
 * "Chain" entry and "Cross Chain Bridge" reaches the "Bridge" entry (listed first) instead.
 */
export function categoryMultiplier(category: string | null): number {
  const c = (category ?? '').toLowerCase();
  for (const [keyword, multiple] of CATEGORY_MULTIPLIERS) {
    const escaped = keyword.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    if (new RegExp(`\\b${escaped}`).test(c)) return multiple;
  }
  return 1.0;
}

/** The chain-diversity multiple: +4% per chain beyond the first, capped at +16%. */
export function chainMultiplier(chains: string[]): number {
  const extra = Math.max(0, chains.length - 1);
  return 1 + Math.min(extra * MODEL.chain_step, MODEL.chain_max_bonus);
}

